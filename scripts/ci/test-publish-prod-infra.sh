# publish <args...>: runs the script, sets rc, out (stdout) and err (stderr). GH_TOKEN is ${token}, unset when empty.
publish() {
  rc=0
  local -a envs=(INFRA_PROD_PRIMARY_URL="${tmp}/primary" INFRA_PROD_TARGET_URL="${tmp}/target.git"
    GH_STATE="${tmp}/gh" PATH="${tmp}/bin:${PATH}")
  [ -z "${token}" ] || envs+=(GH_TOKEN="${token}")
  env -u GH_TOKEN "${envs[@]}" bash "${src}" "$@" >"${tmp}/out" 2>"${tmp}/err" || rc=$?
  out=$(cat "${tmp}/out")
  err=$(cat "${tmp}/err")
}

target_refs() { git -C "${tmp}/target.git" for-each-ref --format='%(refname) %(objectname)' | sort; }
target_sha() { git -C "${tmp}/target.git" rev-parse --verify --quiet "refs/heads/$1"; }
creates() { grep -c " pr create " "${tmp}/gh/log" || true; }

# expect_refusal <name> <args...>: exit 2, target refs unchanged, no PR call.
expect_refusal() {
  local name=$1 before
  shift
  before=$(target_refs)
  publish "$@"
  [ "${rc}" -eq 2 ] || fail "${name}" "exit ${rc}, want 2: ${err}"
  [ "$(target_refs)" = "${before}" ] || fail "${name}" "target refs changed"
  if grep -q " pr " "${tmp}/gh/log"; then fail "${name}" "a PR call was made"; fi
}

