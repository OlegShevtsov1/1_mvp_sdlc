# put <path> <content>: write one file of the primary working tree.
put() {
  mkdir -p "$(dirname "${tmp}/primary/$1")"
  printf '%b' "$2" > "${tmp}/primary/$1"
}

# primary_commit <path> <content>: commit one file change on the primary's checked-out branch.
primary_commit() {
  put "$1" "$2"
  g -C "${tmp}/primary" add -A
  g -C "${tmp}/primary" commit -q -m "change $1"
}

